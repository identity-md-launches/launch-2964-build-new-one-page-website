/**
 * @param {string} lang
 * @param {string} key
 * @param {Record<string, unknown>} [vars]
 * @returns {string}
 */
export function translate(lang, key, vars) {
  const table = STRINGS[lang] || STRINGS.en;
  const template = table[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    const value = vars[name];
    return value === undefined || value === null ? '' : String(value);
  });
}

/** @param {string} key */
export function hasKey(key) {
  return key in STRINGS.en;
}

/** @param {string} lang */
export function localeOf(lang) {
  const found = LANGS.find((entry) => entry.code === lang);
  return found ? found.locale : 'en';
}

/**
 * Resolves the language from the URL, then saved choice, then the browser.
 * @param {string | null | undefined} fromUrl
 * @param {string | null | undefined} saved
 * @param {readonly string[]} browser
 */
export function pickLang(fromUrl, saved, browser) {
  const known = (code) => LANGS.some((entry) => entry.code === code);
  if (fromUrl && known(fromUrl)) return fromUrl;
  if (saved && known(saved)) return saved;
  for (const tag of browser) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (known(base)) return base;
  }
  return 'en';
}
